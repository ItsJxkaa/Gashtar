def set_bg(slide, color):
    bg = slide.background
    fill = bg.fill
    fill.solid()
    fill.fore_color.rgb = color


def add_header(slide, slide_num_str, section_title, dark=False):
    dot = slide.shapes.add_shape(MSO_SHAPE.OVAL, Inches(0.6), Inches(0.42), Inches(0.14), Inches(0.14))
    dot.fill.solid()
    dot.fill.fore_color.rgb = C_RUBY_BRIGHT
    dot.line.fill.background()

    tb = slide.shapes.add_textbox(Inches(0.82), Inches(0.32), Inches(4.5), Inches(0.35))
    tf = tb.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = "GASH.Контроль // AI COMPLIANCE STUDIO"
    p.font.name = "Arial"
    p.font.size = Pt(10)
    p.font.bold = True
    p.font.color.rgb = C_WHITE if dark else C_INK

    tb_r = slide.shapes.add_textbox(Inches(6.5), Inches(0.32), Inches(6.23), Inches(0.35))
    tf_r = tb_r.text_frame
    p_r = tf_r.paragraphs[0]
    p_r.alignment = PP_ALIGN.RIGHT
    p_r.text = f"СЛАЙД {slide_num_str} / 12  ·  {section_title}"
    p_r.font.name = "Consolas"
    p_r.font.size = Pt(9.5)
    p_r.font.color.rgb = C_LIGHT_MUTED if dark else C_MUTED

    line = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0.6), Inches(0.75), Inches(12.133), Inches(0.015))
    line.fill.solid()
    line.fill.fore_color.rgb = RGBColor(0x2D, 0x2D, 0x35) if dark else C_BORDER
    line.line.fill.background()


def add_title_block(slide, kicker, title, subtitle="", dark=False):
    tb = slide.shapes.add_textbox(Inches(0.6), Inches(0.92), Inches(12.133), Inches(1.45))
    tf = tb.text_frame
    tf.word_wrap = True

    p0 = tf.paragraphs[0]
    p0.text = kicker
    p0.font.name = "Consolas"
    p0.font.size = Pt(10.5)
    p0.font.bold = True
    p0.font.color.rgb = C_PINK_ACCENT if dark else C_RUBY_BRIGHT

    p1 = tf.add_paragraph()
    p1.text = title
    p1.font.name = "Arial"
    p1.font.size = Pt(24)
    p1.font.bold = True
    p1.font.color.rgb = C_WHITE if dark else C_INK
    p1.space_before = Pt(4)

    if subtitle:
        p2 = tf.add_paragraph()
        p2.text = subtitle
        p2.font.name = "Arial"
        p2.font.size = Pt(13)
        p2.font.color.rgb = C_LIGHT_MUTED if dark else C_MUTED
        p2.space_before = Pt(4)


def add_card(slide, left, top, width, height, badge, heading, body_lines, mode="light", big_stat=None):
    shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(left), Inches(top), Inches(width), Inches(height))
    shape.adjustments[0] = 0.04
    shape.fill.solid()

    if mode == "dark":
        shape.fill.fore_color.rgb = C_DARK_CARD
        shape.line.color.rgb = RGBColor(0x32, 0x32, 0x3A)
        title_col = C_WHITE
        body_col = C_LIGHT_MUTED
        badge_col = C_PINK_ACCENT
        stat_col = C_PINK_ACCENT
    elif mode == "ruby":
        shape.fill.fore_color.rgb = C_RUBY
        shape.line.color.rgb = C_RUBY_BRIGHT
        title_col = C_WHITE
        body_col = RGBColor(0xF5, 0xE6, 0xEC)
        badge_col = C_WHITE
        stat_col = C_WHITE
    else:
        shape.fill.fore_color.rgb = C_PAPER
        shape.line.color.rgb = C_BORDER
        title_col = C_INK
        body_col = C_MUTED
        badge_col = C_RUBY
        stat_col = C_RUBY_BRIGHT

    tb = slide.shapes.add_textbox(Inches(left + 0.22), Inches(top + 0.18), Inches(width - 0.44), Inches(height - 0.36))
    tf = tb.text_frame
    tf.word_wrap = True

    p_badge = tf.paragraphs[0]
    p_badge.text = badge
    p_badge.font.name = "Consolas"
    p_badge.font.size = Pt(9.5)
    p_badge.font.bold = True
    p_badge.font.color.rgb = badge_col

    if big_stat:
        p_stat = tf.add_paragraph()
        p_stat.text = big_stat
        p_stat.font.name = "Arial"
        p_stat.font.size = Pt(26)
        p_stat.font.bold = True
        p_stat.font.color.rgb = stat_col
        p_stat.space_before = Pt(6)

    p_head = tf.add_paragraph()
    p_head.text = heading
    p_head.font.name = "Arial"
    p_head.font.size = Pt(14.5)
    p_head.font.bold = True
    p_head.font.color.rgb = title_col
    p_head.space_before = Pt(6)

    for line in body_lines:
        p_b = tf.add_paragraph()
        p_b.text = line
        p_b.font.name = "Arial"
        p_b.font.size = Pt(11)
        p_b.font.color.rgb = body_col
        p_b.space_before = Pt(4)


def add_notes(slide, text):
    notes_slide = slide.notes_slide
    tf = notes_slide.notes_text_frame
    tf.text = text


